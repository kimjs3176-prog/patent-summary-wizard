// "왠지"는 올바른 표기이므로, 위 `왠 → 웬` 치환이 잘못 적용되는 것을 방지.
const POST_RESTORE: Array<[RegExp, string]> = [
  [/웬지/g, "왠지"],
];

// 1차 정규화: NFC 통일 (조합형/완성형 불일치로 인한 정규식 매칭 실패 방지).
function normalize(text: string): string {
  try {
    return text.normalize("NFC");
  } catch {
    return text;
  }
}

/**
 * 규칙 기반 한글 오타/맞춤법 치환.
 * - 의미 동일성을 보장하는 명확한 오류만 교정한다.
 * - 코드 블록(```...```) 내부는 보존한다.
 */
export function correctTypos(text: string): string {
  if (!text) return text;
  // 코드 펜스 보호
  const fences: string[] = [];
  let working = normalize(text).replace(/```[\s\S]*?```/g, (m) => {
    fences.push(m);
    return `\u0010CODE${fences.length - 1}\u0011`;
  });

  for (const [pat, rep] of WORD_FIXES) {
    working = working.replace(pat, rep);
  }
  for (const [pat, rep] of POST_RESTORE) {
    working = working.replace(pat, rep);
  }

  // 코드 펜스 복원
  working = working.replace(/\u0010CODE(\d+)\u0011/g, (_, i) => fences[Number(i)] ?? "");
  return working;
}

// 테스트/디버그용 통계: 적용된 규칙 수를 반환.
export function correctTyposWithStats(text: string): { fixed: string; count: number } {
  if (!text) return { fixed: text, count: 0 };
  let count = 0;
  let working = normalize(text);
  for (const [pat, rep] of WORD_FIXES) {
    working = working.replace(pat, (m) => {
      count++;
      return typeof rep === "string" ? m.replace(pat, rep) : m;
    });
  }
  return { fixed: correctTypos(text), count };
}