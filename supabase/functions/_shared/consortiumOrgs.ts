/**
 * 출원인명 비교용 정규화: 띄어쓰기·법인 표기(재단법인, (재), 주식회사, ㈜, (주), 사단법인)·괄호를 지운다.
 * 이름이 같은지 볼 때만 쓰고(포함 여부로 보지 않는다), '건국대학교 산학협력단'과 '건국대학교 글로컬산학협력단'은 다르게 남는다.
 */
export function normalizeApplicant(name: string): string {
  return name
    .replace(/재단법인|사단법인|주식회사|\(재\)|\(사\)|\(주\)|㈜/g, "")
    .replace(/[\s·.,()（）]/g, "")
    .trim();
}

export function orgNames(org: ConsortiumOrg): string[] {
  return [org.name, ...(org.aliases ?? [])];
}
